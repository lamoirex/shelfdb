int main(int argc, char* argv[]) {
    std::string base = argc > 1 ? argv[1] : "books";

    Database db;
    if (!db.create(base)) {
        std::cerr << "Не удалось создать базу " << base << std::endl;
        return 1;
    }

    int id = 1;
    for (const Sample& s : BOOKS) {
        if (std::string(s.title).size() > TITLE_LEN || std::string(s.author).size() > AUTHOR_LEN) {
            std::cerr << "Слишком длинная строка: " << s.title << std::endl;
            return 1;
        }
        db.add(makeBook(id++, s.title, s.author, s.year, s.price, s.available));
    }
    db.close();

    std::cout << "Создана база " << base << ".dat: " << BOOKS.size() << " книг" << std::endl;
    return 0;
}
